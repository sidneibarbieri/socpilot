"""Compute action-list extraction diagnostics from a completed run.

The primary prompt requests a JSON object containing catalog identifiers. This
tool measures parse errors, identifiers outside the catalog, empty plans, and
whether the completion-token cap bound. Every number comes from preserved
per-cell outputs and the run ledger.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

_PARSE_ERROR_EXCEPTIONS = {"LLMResponseParseError", "LLMAdapterError"}


def _cells_for_run(outputs_dir: Path, run_ids: set[str]) -> list[dict]:
    cells = []
    for path in sorted(outputs_dir.rglob("verifier_output_llm_*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        if payload.get("experiment_run_id") in run_ids:
            cells.append(payload)
    if not cells:
        raise FileNotFoundError(
            f"No cells for runs {sorted(run_ids)} under {outputs_dir}"
        )
    return cells


def _parse_error_count(ledger_path: Path, run_ids: set[str]) -> int:
    ledger = json.loads(ledger_path.read_text(encoding="utf-8"))
    entries = (
        ledger
        if isinstance(ledger, list)
        else ledger.get("entries", ledger.get("cells", []))
    )
    return sum(
        1
        for entry in entries
        if isinstance(entry, dict)
        and entry.get("run_id") in run_ids
        and str(entry.get("exception_type") or "") in _PARSE_ERROR_EXCEPTIONS
    )


def build_diagnostics(
    outputs_dir: Path, ledger_path: Path, run_ids: set[str], token_cap: int
) -> dict:
    cells = _cells_for_run(outputs_dir, run_ids)
    action_counts = [len(cell.get("llm_actions", [])) for cell in cells]
    hallucinated = sum(
        int(cell.get("llm_hallucinated_action_count", 0)) for cell in cells
    )
    completion_tokens = []
    for cell in cells:
        usage = cell.get("llm_usage") or {}
        tokens = usage.get("completion_tokens") or usage.get("output_tokens")
        if tokens is not None:
            completion_tokens.append(int(tokens))
    return {
        "schema_version": 2,
        "run_ids": sorted(run_ids),
        "cell_count": len(cells),
        "parse_error_count": _parse_error_count(ledger_path, run_ids),
        "hallucinated_action_count": hallucinated,
        "empty_plan_count": sum(1 for count in action_counts if count == 0),
        "min_plan_length": min(action_counts),
        "max_plan_length": max(action_counts),
        "max_completion_tokens": max(completion_tokens) if completion_tokens else 0,
        "completion_token_cap": token_cap,
    }


def render_macros(diagnostics: dict) -> str:
    values = {
        "ProjectionParseErrors": diagnostics["parse_error_count"],
        "ProjectionOutOfCatalog": diagnostics["hallucinated_action_count"],
        "ProjectionEmptyPlans": diagnostics["empty_plan_count"],
        "ProjectionMinPlanLength": diagnostics["min_plan_length"],
        "ProjectionMaxCompletionTokens": diagnostics["max_completion_tokens"],
        "ProjectionTokenCap": diagnostics["completion_token_cap"],
    }
    return "\n".join(
        f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in values.items()
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outputs-incidents-dir", type=Path, required=True)
    parser.add_argument("--ledger-json", type=Path, required=True)
    parser.add_argument("--run-id", required=True, help="Comma-separated run ids.")
    parser.add_argument("--token-cap", type=int, required=True)
    parser.add_argument("--output-json", type=Path, required=True)
    parser.add_argument("--macros-output", type=Path)
    args = parser.parse_args(argv)

    run_ids = {rid.strip() for rid in str(args.run_id).split(",") if rid.strip()}
    diagnostics = build_diagnostics(
        args.outputs_incidents_dir.resolve(),
        args.ledger_json.resolve(),
        run_ids,
        args.token_cap,
    )
    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_json.write_text(
        json.dumps(diagnostics, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(f"Wrote projection diagnostics: {args.output_json}")
    if args.macros_output:
        args.macros_output.parent.mkdir(parents=True, exist_ok=True)
        header = "% Generated by build_projection_diagnostics.py\n"
        args.macros_output.write_text(
            header + render_macros(diagnostics) + "\n", encoding="utf-8"
        )
        print(f"Wrote projection macros: {args.macros_output}")


if __name__ == "__main__":
    main()

"""Omission rates of mandatory rules, grouped by the action each rule requires.

Reads the preserved per-cell family outcomes of a completed measurement and the
declared policy constraints. A rule's omission rate is violated applicable
decisions divided by applicable decisions; grouping pools rules that require
the same catalog action. Writes LaTeX macros for the paper.

Usage:
    bash reproduce.sh action-omission
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

import yaml

MACRO_ACTIONS = {"block_egress": "BlockEgress", "isolate_host": "IsolateHost"}


@dataclass(frozen=True)
class ActionOmission:
    action: str
    rule_count: int
    applicable: int
    omitted: int

    @property
    def rate_pct(self) -> float:
        return 100.0 * self.omitted / self.applicable


def mandatory_rule_actions(constraints_path: Path) -> dict[str, str]:
    rules = yaml.safe_load(constraints_path.read_text(encoding="utf-8"))
    return {rule["rule_id"]: rule["action"] for rule in rules if rule["type"] == "mandatory"}


def read_cells(cells_path: Path) -> list[dict]:
    lines = cells_path.read_text(encoding="utf-8").splitlines()
    return [json.loads(line) for line in lines if line.strip()]


def count_rule_outcomes(cells: list[dict]) -> tuple[Counter, Counter]:
    applicable: Counter = Counter()
    violated: Counter = Counter()
    for cell in cells:
        for family in cell["family_outcomes"]:
            for outcome in family.get("rule_outcomes", []):
                if outcome["applicable"]:
                    applicable[outcome["rule_id"]] += 1
                    violated[outcome["rule_id"]] += int(outcome["violated"])
    return applicable, violated


def strata(cells: list[dict]) -> dict[str, list[dict]]:
    """Model-by-prompt cells and acquisition batches, the paper's reporting strata."""
    groups: dict[str, list[dict]] = {}
    for cell in cells:
        groups.setdefault(f"{cell['deployment']}|{cell['arm']}", []).append(cell)
        groups.setdefault(cell["corpus_stratum"], []).append(cell)
    return groups


def stratum_rates(
    cells: list[dict], rule_actions: dict[str, str], action: str
) -> dict[str, float]:
    rates = {}
    for name, members in strata(cells).items():
        applicable, violated = count_rule_outcomes(members)
        (omission,) = [
            group
            for group in group_by_action(rule_actions, applicable, violated)
            if group.action == action
        ]
        rates[name] = omission.rate_pct
    return rates


def group_by_action(
    rule_actions: dict[str, str], applicable: Counter, violated: Counter
) -> list[ActionOmission]:
    groups: dict[str, list[str]] = {}
    for rule_id, action in rule_actions.items():
        groups.setdefault(action, []).append(rule_id)
    return [
        ActionOmission(
            action=action,
            rule_count=len(rule_ids),
            applicable=sum(applicable[rule_id] for rule_id in rule_ids),
            omitted=sum(violated[rule_id] for rule_id in rule_ids),
        )
        for action, rule_ids in sorted(groups.items())
    ]


def render_macros(
    omissions: list[ActionOmission],
    block_rates: dict[str, float],
    isolate_rates: dict[str, float],
    source_sha256: str,
) -> str:
    lines = [f"% Generated by build_action_omission_report.py; cells sha256 {source_sha256}"]
    exceeding = sum(block_rates[name] > isolate_rates[name] for name in block_rates)
    lines += [
        rf"\newcommand{{\OmissionStrataCount}}{{{len(block_rates)}}}",
        rf"\newcommand{{\OmissionBlockExceedsStrata}}{{{exceeding}}}",
        rf"\newcommand{{\OmissionBlockEgressMinPct}}{{{min(block_rates.values()):.1f}}}",
        rf"\newcommand{{\OmissionBlockEgressMaxPct}}{{{max(block_rates.values()):.1f}}}",
        rf"\newcommand{{\OmissionIsolateHostMinPct}}{{{min(isolate_rates.values()):.1f}}}",
        rf"\newcommand{{\OmissionIsolateHostMaxPct}}{{{max(isolate_rates.values()):.1f}}}",
    ]
    for omission in omissions:
        name = MACRO_ACTIONS.get(omission.action)
        if name is None:
            continue
        lines += [
            rf"\newcommand{{\Omission{name}Rules}}{{{omission.rule_count}}}",
            rf"\newcommand{{\Omission{name}Applicable}}{{{omission.applicable:,}}}",
            rf"\newcommand{{\Omission{name}Pct}}{{{omission.rate_pct:.1f}}}",
        ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cells", type=Path, required=True)
    parser.add_argument("--constraints", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    cells = read_cells(args.cells)
    rule_actions = mandatory_rule_actions(args.constraints)
    applicable, violated = count_rule_outcomes(cells)
    omissions = group_by_action(rule_actions, applicable, violated)
    block_rates = stratum_rates(cells, rule_actions, "block_egress")
    isolate_rates = stratum_rates(cells, rule_actions, "isolate_host")
    source_sha256 = hashlib.sha256(args.cells.read_bytes()).hexdigest()
    macros = render_macros(omissions, block_rates, isolate_rates, source_sha256)
    args.output.write_text(macros, encoding="utf-8")
    for omission in omissions:
        print(f"{omission.action}: {omission.omitted}/{omission.applicable} "
              f"({omission.rate_pct:.1f}%) over {omission.rule_count} rules")


if __name__ == "__main__":
    main()

"""Render judge-ablation macros from the frozen ablation report.

The paper consumes these numbers; none is hand-typed. The ablation compares a
per-rule judge prompt against the frozen judge prompt on the same stratified
subset. Both error directions are rendered, because a false-accept rate alone
cannot distinguish a discriminating judge from one that rejects every plan.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def render_macros(report: dict) -> str:
    ablation = report["ablation_judge"]
    frozen = report["frozen_judge_on_same_sample"]
    values = {
        "AblationScored": report["scored"],
        "AblationFADenominator": ablation["false_accept_denominator"],
        "AblationFRDenominator": ablation["false_reject_denominator"],
        "AblationStrongJudgeFAPct": f"{ablation['false_accept_rate'] * 100:.0f}",
        "AblationFrozenJudgeFAPct": f"{frozen['false_accept_rate'] * 100:.0f}",
        "AblationStrongJudgeFRCount": ablation["false_reject"],
        "AblationStrongJudgeFRPct": f"{ablation['false_reject_rate'] * 100:.0f}",
        "AblationFrozenJudgeFRPct": f"{frozen['false_reject_rate'] * 100:.0f}",
    }
    return "\n".join(
        f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in values.items()
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ablation-report-json", required=True)
    parser.add_argument("--macros-output", required=True)
    args = parser.parse_args(argv)

    report = json.loads(Path(args.ablation_report_json).read_text(encoding="utf-8"))
    out = Path(args.macros_output)
    out.parent.mkdir(parents=True, exist_ok=True)
    header = "% Generated by render_judge_ablation_tex.py\n"
    out.write_text(header + render_macros(report) + "\n", encoding="utf-8")
    print(f"Wrote judge-ablation macros: {out}")


if __name__ == "__main__":
    main()

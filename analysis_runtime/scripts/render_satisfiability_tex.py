"""Render rule-satisfiability macros from the satisfiability report.

The report is recomputable from any package: the rule set ships in
artifact_data/global/constraints.yaml, and co-application depends only on event
categories, which the publication projection preserves.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def render_macros(report: dict) -> str:
    values = {
        "SatRuleCount": report["rule_count"],
        "SatCertainConflicts": report["certain_unconditional_conflict_count"],
        "SatPossibleConflicts": report["possible_unconditional_conflict_count"],
        "SatApprovalConflicts": report["approval_dependent_conflict_count"],
        "SatCorpusIncidents": report["corpus_incident_count"],
        "SatPossibleAffectedIncidents": report["unconditional_affected_incident_count"],
        "SatApprovalAffectedIncidents": report["approval_dependent_affected_incident_count"],
    }
    return "\n".join(f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in values.items())


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--satisfiability-report-json", required=True)
    parser.add_argument("--macros-output", required=True)
    args = parser.parse_args(argv)
    report = json.loads(Path(args.satisfiability_report_json).read_text(encoding="utf-8"))
    out = Path(args.macros_output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("% Generated by render_satisfiability_tex.py\n" + render_macros(report) + "\n", encoding="utf-8")
    print(f"Wrote satisfiability macros: {out}")


if __name__ == "__main__":
    main()
